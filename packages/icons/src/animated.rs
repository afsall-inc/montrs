//! Animated icon component.
//!
//! Wraps [`Icon`] with hover-triggered CSS animations. Each icon gets an
//! animation profile (path draw, scale, rotate, shake, etc.) based on its
//! name, matching the Lucide Animated Icons behavior.

use leptos::prelude::*;
use leptos::text_prop::TextProp;
use crate::glyph::Glyph;
use crate::icon::{render_svg, DEFAULT_SIZE, DEFAULT_FILL, DEFAULT_STROKE, DEFAULT_STROKE_WIDTH};

/// Animation profile for a glyph.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AnimationProfile {
    /// Path drawing: stroke-dasharray animation (default for most icons)
    PathDraw,
    /// Scale pulse (e.g., heart)
    Pulse,
    /// Rotation shake (e.g., bell)
    Shake,
    /// Continuous rotation (e.g., loader, cog)
    Spin,
    /// Nod/bounce (e.g., search)
    Nod,
    /// No animation
    None,
}

/// Animated icon component with hover-triggered animation.
///
/// Each icon animates based on its profile (path draw, pulse, shake, etc.)
#[component]
pub fn AnimatedIcon(
    /// The icon to render.
    #[prop(into)] glyph: Signal<Glyph>,
    /// CSS class for the SVG element.
    #[prop(into, optional)] class: Option<TextProp>,
    /// Width and height in pixels (default: `"24"`).
    #[prop(into, optional)] size: Option<TextProp>,
    /// SVG fill color (default: `"none"`).
    #[prop(into, optional)] fill: Option<TextProp>,
    /// SVG stroke color (default: `"currentColor"`).
    #[prop(into, optional)] stroke: Option<TextProp>,
    /// SVG stroke width (default: `"1.5"`).
    #[prop(into, optional)] stroke_width: Option<TextProp>,
) -> impl IntoView {
    let (hovered, set_hovered) = signal(false);
    let profile = Memo::new(move |_| animation_profile(glyph.get()));

    let svg = TextProp::from(move || glyph.get().svg());
    let class = class.unwrap_or_else(|| "".into());
    let size = size.unwrap_or_else(|| DEFAULT_SIZE.into());
    let size2 = size.clone();
    let fill = fill.unwrap_or_else(|| DEFAULT_FILL.into());
    let stroke = stroke.unwrap_or_else(|| DEFAULT_STROKE.into());
    let stroke_width = stroke_width.unwrap_or_else(|| DEFAULT_STROKE_WIDTH.into());

    let wrapper_class = move || {
        let mut c = class.get();
        let p = profile.get();
        let h = hovered.get();
        match p {
            AnimationProfile::PathDraw => {
                c.push_str(" icon-ani-path-draw");
                if h { c.push_str(" icon-ani-active"); }
            }
            AnimationProfile::Pulse => {
                c.push_str(" icon-ani-pulse");
                if h { c.push_str(" icon-ani-active"); }
            }
            AnimationProfile::Shake => {
                c.push_str(" icon-ani-shake");
                if h { c.push_str(" icon-ani-active"); }
            }
            AnimationProfile::Spin => {
                c.push_str(" icon-ani-spin");
                if h { c.push_str(" icon-ani-active"); }
            }
            AnimationProfile::Nod => {
                c.push_str(" icon-ani-nod");
                if h { c.push_str(" icon-ani-active"); }
            }
            AnimationProfile::None => {}
        }
        c
    };

    view! {
        <span
            class=wrapper_class
            style="display: inline-flex; cursor: pointer;"
            on:mouseenter=move |_| set_hovered.set(true)
            on:mouseleave=move |_| set_hovered.set(false)
        >
            <svg
              xmlns="http://www.w3.org/2000/svg"
              class="icon-ani-svg"
              width=move || size.get()
              height=move || size2.get()
              viewBox="0 0 24 24"
              fill=move || fill.get()
              stroke=move || stroke.get()
              stroke-width=move || stroke_width.get()
              stroke-linecap="round"
              stroke-linejoin="round"
              inner_html=move || svg.get()
            />
        </span>
    }
}

/// Determine the animation profile for a glyph based on its name.
fn animation_profile(glyph: Glyph) -> AnimationProfile {
    let name = glyph.name();
    // Spin: continuous rotation icons
    if name.contains("Loader") || name.contains("Spinner") || name.contains("Cog")
        || name.contains("Refresh") || name.contains("Sync") || name.contains("Rotate")
        || name == "LoaderCircle"
    {
        return AnimationProfile::Spin;
    }
    // Pulse: heartbeat/like icons
    if name.contains("Heart") || name.contains("Thumbs") || name.contains("Activity")
        || name == "Activity"
    {
        return AnimationProfile::Pulse;
    }
    // Shake: notification/alert icons
    if name.contains("Bell") || name.contains("Alert") || name.contains("Alarm")
        || name.contains("Notification") || name == "Moon"
    {
        return AnimationProfile::Shake;
    }
    // Nod: search/navigation icons
    if name.contains("Search") || name.contains("Navigation") || name.contains("Compass")
        || name.contains("Locate")
    {
        return AnimationProfile::Nod;
    }
    // Default: path drawing for most icons
    AnimationProfile::PathDraw
}

